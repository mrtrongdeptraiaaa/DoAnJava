    private void loadCombo(JComboBox<String> cbo, String sql) {
        cbo.removeAllItems();
        try (Connection con = PhamDucTrongGiaoDien.dal.DBConnection;
             PreparedStatement ps = con.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) cbo.addItem(rs.getString(1));
        } catch (SQLException ex) {
            showError(ex);
        }
    }

    private void loadData() {
        model.setRowCount(0);
        String sql = "SELECT MaSinhVien, MaMonHoc, LanThi, Diem FROM KetQua ORDER BY MaSinhVien, MaMonHoc, LanThi";
        try (Connection con = PhamDucTrongGiaoDien.dal.DBConnection;
             PreparedStatement ps = con.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString(1), rs.getString(2), rs.getInt(3), rs.getDouble(4)
                });
            }
        } catch (SQLException ex) {
            showError(ex);
        }
    }

    private void fillFormFromRow() {
        int row = tblKetQua.getSelectedRow();
        if (row < 0) return;
        cboMaSinhVien.setSelectedItem(model.getValueAt(row, 0).toString());
        cboMaMonHoc.setSelectedItem(model.getValueAt(row, 1).toString());
        txtLanThi.setText(model.getValueAt(row, 2).toString());
        txtDiem.setText(model.getValueAt(row, 3).toString());
        // Khóa chính gồm 3 trường nên khóa luôn các ô khóa khi đang sửa
        cboMaSinhVien.setEnabled(false);
        cboMaMonHoc.setEnabled(false);
        txtLanThi.setEnabled(false);
        btnSua.setEnabled(true);
        btnXoa.setEnabled(true);
    }

    private void clearForm() {
        if (cboMaSinhVien.getItemCount() > 0) cboMaSinhVien.setSelectedIndex(0);
        if (cboMaMonHoc.getItemCount() > 0) cboMaMonHoc.setSelectedIndex(0);
        txtLanThi.setText("");
        txtDiem.setText("");
        cboMaSinhVien.setEnabled(true);
        cboMaMonHoc.setEnabled(true);
        txtLanThi.setEnabled(true);
        tblKetQua.clearSelection();
        btnSua.setEnabled(false);
        btnXoa.setEnabled(false);
        txtLanThi.requestFocus();
    }

    private boolean validateInput() {
        try {
            int lanThi = Integer.parseInt(txtLanThi.getText().trim());
            if (lanThi <= 0) throw new NumberFormatException();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Lần thi phải là số nguyên dương!");
            return false;
        }
        try {
            double diem = Double.parseDouble(txtDiem.getText().trim());
            if (diem < 0 || diem > 10) throw new NumberFormatException();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Điểm phải là số từ 0 đến 10!");
            return false;
        }
        if (cboMaSinhVien.getSelectedItem() == null || cboMaMonHoc.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sinh viên và môn học!");
            return false;
        }
        return true;
    }

    private void showError(SQLException ex) {
        JOptionPane.showMessageDialog(this, "Lỗi CSDL: " + ex.getMessage());
    }

