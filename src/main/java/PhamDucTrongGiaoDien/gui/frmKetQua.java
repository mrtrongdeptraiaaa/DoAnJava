    private void btnThem5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThem5ActionPerformed
        if (!validateInput()) return;
        String sql = "INSERT INTO KetQua (MaSinhVien, MaMonHoc, LanThi, Diem) VALUES (?, ?, ?, ?)";
        try (Connection con = PhamDucTrongGiaoDien.dal.DBConnection;
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, cboMaSinhVien.getSelectedItem().toString());
            ps.setString(2, cboMaMonHoc.getSelectedItem().toString());
            ps.setInt(3, Integer.parseInt(txtLanThi.getText().trim()));
            ps.setDouble(4, Double.parseDouble(txtDiem.getText().trim()));
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Thêm kết quả thành công!");
            loadData();
            clearForm();
        } catch (SQLException ex) {
            if (ex.getErrorCode() == 2627) JOptionPane.showMessageDialog(this, "Kết quả này đã tồn tại!");
            else showError(ex);
        }
    }//GEN-LAST:event_btnThem5ActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        if (!validateInput()) return;
        String sql = "UPDATE KetQua SET Diem = ? WHERE MaSinhVien = ? AND MaMonHoc = ? AND LanThi = ?";
        try (Connection con = PhamDucTrongGiaoDien.dal.DBConnection;
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setDouble(1, Double.parseDouble(txtDiem.getText().trim()));
            ps.setString(2, cboMaSinhVien.getSelectedItem().toString());
            ps.setString(3, cboMaMonHoc.getSelectedItem().toString());
            ps.setInt(4, Integer.parseInt(txtLanThi.getText().trim()));
            if (ps.executeUpdate() > 0) JOptionPane.showMessageDialog(this, "Cập nhật thành công!");
            loadData();
            clearForm();
        } catch (SQLException ex) {
            showError(ex);
        }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        int c = JOptionPane.showConfirmDialog(this, "Bạn có chắc muốn xóa kết quả này?",
                "Xác nhận", JOptionPane.YES_NO_OPTION);
        if (c != JOptionPane.YES_OPTION) return;
        String sql = "DELETE FROM KetQua WHERE MaSinhVien = ? AND MaMonHoc = ? AND LanThi = ?";
        try (Connection con = PhamDucTrongGiaoDien.dal.DBConnection;
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, cboMaSinhVien.getSelectedItem().toString());
            ps.setString(2, cboMaMonHoc.getSelectedItem().toString());
            ps.setInt(3, Integer.parseInt(txtLanThi.getText().trim()));
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Xóa thành công!");
            loadData();
            clearForm();
        } catch (SQLException ex) {
            showError(ex);
        }
    }//GEN-LAST:event_btnXoaActionPerformed

